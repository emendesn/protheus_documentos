SELECT SD2.D2_FILIAL, SD2.D2_DOC, SD2.D2_SERIE, SD2.D2_CLIENTE, SD2.D2_LOJA, SD2.D2_COD, SD2.D2_ITEM, SD2.D2_NUMSEQ, 
SD2.D2_CF, SD2.D2_QUANT, SD2.D2_EMISSAO, SD2.D2_PICM, SD2.D2_VALICM, SD2.D2_BASEICM, 
 SD2.D2_EST, SD2.D2_TIPO, SD2.D2_BRICMS, SD2.D2_TES, SD2.D2_LOTECTL, SD2.D2_NUMLOTE, SD2.D2_DTVALID
FROM SD2130 SD2, SF4130 SF4, SB1130 SB1
WHERE SD2.D2_FILIAL = '01' AND	  
SD2.D2_EMISSAO >= '20100101' AND
SD2.D2_EMISSAO <= '20151231' AND		        	                     
SD2.D2_TIPO = 'N' AND
SD2.D2_BRICMS <> 0 AND
SD2.D_E_L_E_T_ <> '*' AND
SF4.F4_CODIGO = D2_TES AND
SF4.D_E_L_E_T_ <> '*' AND
SB1.B1_COD = D2_COD AND
SB1.D_E_L_E_T_ <> '*'
