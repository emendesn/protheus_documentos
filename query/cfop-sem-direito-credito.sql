--CFOP SEM DIREITO A CREDITO DE ICMS/IPI/PIS/COFINS
--LIVRO FISCAL - (VLR.CONTABIL/OUTRAS ICMS/OUTRAS IPI)
SELECT F4_CF,F4_ICM,F4_CREDICM,F4_LFICM,F4_IPI,F4_CREDIPI,F4_LFIPI,F4_PISCOF,F4_PISCRED,F4_CODIGO,X5_DESCRI
--UPDATE SF4910 SET F4_CREDICM='N',F4_LFICM='O',F4_CREDIPI='N',F4_LFIPI='O',F4_PISCOF='4',F4_PISCRED='3'
FROM SF4990 SF4
INNER JOIN SX5990 SX5 ON F4_CF=SUBSTRING(X5_CHAVE,1,4)
WHERE F4_CODIGO <= '500' 
AND SUBSTRING(F4_CF,2,3) IN(
'302',
'303',
'407',
'551',
'556',
'901',
'902',
'908',
'909',
'912',
'913',
'933')
ORDER BY F4_CF

