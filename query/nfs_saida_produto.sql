SELECT B1_COD,B1_DESC,B1_CRICMS,D2_TES,F4_CF,F4_TEXTO
FROM SD2130 SD2, SF4130 SF4, SB1130 SB1
WHERE SD2.D2_FILIAL = '01' AND	  
SD2.D2_EMISSAO >= '20100101' AND
SD2.D2_EMISSAO <= '20151231' AND		        	                     
SD2.D2_TIPO = 'N' AND
SD2.D2_BRICMS <> 0 AND
SD2.D_E_L_E_T_ <> '*' AND
SF4.F4_CODIGO = D2_TES AND
SF4.D_E_L_E_T_ <> '*' AND
SB1.B1_COD = D2_COD AND
SB1.D_E_L_E_T_ <> '*'
GROUP BY B1_COD,B1_DESC,B1_CRICMS,D2_TES,F4_CF,F4_TEXTO
